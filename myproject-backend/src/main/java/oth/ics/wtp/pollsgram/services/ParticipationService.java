package oth.ics.wtp.pollsgram.services;

import oth.ics.wtp.pollsgram.dtos.AnswerResponse;
import oth.ics.wtp.pollsgram.dtos.AnswerSubmissionRequest;
import oth.ics.wtp.pollsgram.dtos.ParticipationResponse;
import oth.ics.wtp.pollsgram.dtos.PollSubmissionRequest;
import oth.ics.wtp.pollsgram.dtos.QuestionResultResponse;
import oth.ics.wtp.pollsgram.entities.Answer;
import oth.ics.wtp.pollsgram.entities.Participation;
import oth.ics.wtp.pollsgram.entities.Poll;
import oth.ics.wtp.pollsgram.entities.Question;
import oth.ics.wtp.pollsgram.entities.QuestionType;
import oth.ics.wtp.pollsgram.entities.User;
import oth.ics.wtp.pollsgram.exceptions.BadRequestException;
import oth.ics.wtp.pollsgram.exceptions.ForbiddenException;
import oth.ics.wtp.pollsgram.repositories.InvitationRepository;
import oth.ics.wtp.pollsgram.repositories.ParticipationRepository;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;

@Service
public class ParticipationService {

    private final ParticipationRepository participationRepository;
    private final InvitationRepository invitationRepository;
    private final PollService pollService;
    private final UserService userService;

    public ParticipationService(
            ParticipationRepository participationRepository,
            InvitationRepository invitationRepository,
            PollService pollService,
            UserService userService
    ) {
        this.participationRepository = participationRepository;
        this.invitationRepository = invitationRepository;
        this.pollService = pollService;
        this.userService = userService;
    }

    // generated by AI
    @Transactional
    public void submitPoll(Long pollId, PollSubmissionRequest request, String username) {
        Poll poll = pollService.findEntityById(pollId);
        User participant = userService.findEntityByUsername(username);

        validateSubmission(poll, participant, request);

        Participation participation = new Participation(poll, participant);

        for (AnswerSubmissionRequest answerRequest : request.getAnswers()) {
            Question question = findQuestionInPoll(poll, answerRequest.getQuestionId());

            Answer answer = new Answer(question);
            fillAnswerValue(answer, question, answerRequest);

            participation.addAnswer(answer);
        }

        participationRepository.save(participation);
    }

    // generated by AI
    public List<ParticipationResponse> getParticipationsForPoll(Long pollId, String username) {
        Poll poll = pollService.findEntityById(pollId);
        User currentUser = userService.findEntityByUsername(username);

        if (!poll.getCreator().getId().equals(currentUser.getId())) {
            throw new ForbiddenException("Only the poll creator can view submissions");
        }

        if (!poll.isFinished()) {
            throw new BadRequestException("Poll must be finished before viewing submissions");
        }

        return participationRepository.findByPoll(poll)
                .stream()
                .map(this::toParticipationResponse)
                .toList();
    }

    public List<QuestionResultResponse> getResultsForPoll(Long pollId, String username) {
        Poll poll = pollService.findEntityById(pollId);
        User currentUser = userService.findEntityByUsername(username);

        if (!poll.getCreator().getId().equals(currentUser.getId())) {
            throw new ForbiddenException("Only the poll creator can view results");
        }

        if (!poll.isFinished()) {
            throw new BadRequestException("Poll must be finished before viewing results");
        }

        List<Participation> participations = participationRepository.findByPoll(poll);

        return poll.getQuestions()
                .stream()
                .map(question -> calculateResultForQuestion(question, participations))
                .toList();
    }

    public List<ParticipationResponse> getMyParticipations(String username) {
        User currentUser = userService.findEntityByUsername(username);

        return participationRepository.findByParticipant(currentUser)
                .stream()
                .map(this::toParticipationResponse)
                .toList();
    }

    private void validateSubmission(
            Poll poll,
            User participant,
            PollSubmissionRequest request
    ) {
        if (poll.isFinished()) {
            throw new BadRequestException("Cannot submit answers to a finished poll");
        }

        if (poll.getCreator().getUsername().equals(participant.getUsername())) {
            throw new BadRequestException("You cannot participate in your own poll");
        }

        if (!invitationRepository.existsByPollAndInvitee(poll, participant)) {
            throw new ForbiddenException("You are not invited to this poll");
        }

        if (participationRepository.existsByPollAndParticipant(poll, participant)) {
            throw new BadRequestException("You have already submitted this poll");
        }

        if (request.getAnswers() == null || request.getAnswers().isEmpty()) {
            throw new BadRequestException("At least one answer is required");
        }

        if (request.getAnswers().size() != poll.getQuestions().size()) {
            throw new BadRequestException("You must answer all questions");
        }
    }

    private Question findQuestionInPoll(Poll poll, Long questionId) {
        if (questionId == null) {
            throw new BadRequestException("Question id is required");
        }

        return poll.getQuestions()
                .stream()
                .filter(question -> question.getId().equals(questionId))
                .findFirst()
                .orElseThrow(() -> new BadRequestException("Question does not belong to this poll"));
    }

    private void fillAnswerValue(
            Answer answer,
            Question question,
            AnswerSubmissionRequest request
    ) {
        if (question.getType() == QuestionType.BOOLEAN) {
            if (request.getBooleanValue() == null) {
                throw new BadRequestException("Boolean answer is required");
            }

            answer.setBooleanValue(request.getBooleanValue());
            return;
        }

        if (question.getType() == QuestionType.NUMBER) {
            Integer value = request.getNumericValue();

            if (value == null) {
                throw new BadRequestException("Numeric answer is required");
            }

            if (value < 1 || value > 5) {
                throw new BadRequestException("Numeric answer must be between 1 and 5");
            }

            answer.setNumericValue(value);
            return;
        }

        if (question.getType() == QuestionType.TEXT) {
            if (request.getTextValue() == null || request.getTextValue().isBlank()) {
                throw new BadRequestException("Text answer is required");
            }

            answer.setTextValue(request.getTextValue());
        }
    }

    private ParticipationResponse toParticipationResponse(Participation participation) {
        List<AnswerResponse> answerResponses = participation.getAnswers()
                .stream()
                .map(this::toAnswerResponse)
                .toList();

        return new ParticipationResponse(
                participation.getId(),
                participation.getParticipant().getUsername(),
                participation.getSubmittedAt(),
                answerResponses
        );
    }

    private AnswerResponse toAnswerResponse(Answer answer) {
        return new AnswerResponse(
                answer.getQuestion().getId(),
                answer.getQuestion().getText(),
                answer.getTextValue(),
                answer.getBooleanValue(),
                answer.getNumericValue()
        );
    }

    private QuestionResultResponse calculateResultForQuestion(
            Question question,
            List<Participation> participations
    ) {
        List<Answer> answersForQuestion = participations
                .stream()
                .flatMap(participation -> participation.getAnswers().stream())
                .filter(answer -> answer.getQuestion().getId().equals(question.getId()))
                .toList();

        if (question.getType() == QuestionType.BOOLEAN) {
            long trueCount = answersForQuestion
                    .stream()
                    .filter(answer -> Boolean.TRUE.equals(answer.getBooleanValue()))
                    .count();

            long falseCount = answersForQuestion
                    .stream()
                    .filter(answer -> Boolean.FALSE.equals(answer.getBooleanValue()))
                    .count();

            return new QuestionResultResponse(
                    question.getId(),
                    question.getText(),
                    question.getType(),
                    trueCount,
                    falseCount,
                    null,
                    null
            );
        }

        if (question.getType() == QuestionType.NUMBER) {
            double average = answersForQuestion
                    .stream()
                    .map(Answer::getNumericValue)
                    .filter(value -> value != null)
                    .mapToInt(Integer::intValue)
                    .average()
                    .orElse(0.0);

            return new QuestionResultResponse(
                    question.getId(),
                    question.getText(),
                    question.getType(),
                    null,
                    null,
                    average,
                    null
            );
        }

        List<String> textAnswers = answersForQuestion
                .stream()
                .map(Answer::getTextValue)
                .filter(value -> value != null && !value.isBlank())
                .toList();

        return new QuestionResultResponse(
                question.getId(),
                question.getText(),
                question.getType(),
                null,
                null,
                null,
                textAnswers
        );
    }
}