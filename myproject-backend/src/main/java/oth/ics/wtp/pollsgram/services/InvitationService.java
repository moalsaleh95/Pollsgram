package oth.ics.wtp.pollsgram.services;

import oth.ics.wtp.pollsgram.dtos.InvitationRequest;
import oth.ics.wtp.pollsgram.entities.*;
import oth.ics.wtp.pollsgram.exceptions.*;
import oth.ics.wtp.pollsgram.repositories.InvitationRepository;
import org.springframework.stereotype.Service;
import oth.ics.wtp.pollsgram.dtos.PollResponse;
import oth.ics.wtp.pollsgram.mappers.PollMapper;
import oth.ics.wtp.pollsgram.repositories.ParticipationRepository;

import java.util.Comparator;
import java.util.List;

@Service
public class InvitationService {
    private final ParticipationRepository participationRepository;
    private final InvitationRepository invitationRepository;
    private final PollService pollService;
    private final UserService userService;

    public InvitationService(
            InvitationRepository invitationRepository,
            ParticipationRepository participationRepository,
            PollService pollService,
            UserService userService
    ) {
        this.invitationRepository = invitationRepository;
        this.participationRepository = participationRepository;
        this.pollService = pollService;
        this.userService = userService;
    }

    public void inviteUser(
            Long pollId,
            InvitationRequest request,
            String username
    ) {

        Poll poll = pollService.findEntityById(pollId);

        User creator =
                userService.findEntityByUsername(username);

        if (request.getUsername() == null || request.getUsername().isBlank()) {
            throw new BadRequestException("Username is required");
        }

        User invitee =
                userService.findEntityByUsername(
                        request.getUsername()
                );

        if (!poll.getCreator().getUsername().equals(creator.getUsername())) {
            throw new ForbiddenException("Only creator can invite users");
        }

        if (creator.getUsername().equals(invitee.getUsername())) {
            throw new BadRequestException("You cannot invite yourself");
        }

        if (invitationRepository.existsByPollAndInvitee(
                poll,
                invitee
        )) {
            throw new BadRequestException(
                    "User already invited"
            );
        }

        Invitation invitation =
                new Invitation(poll, invitee);

        invitationRepository.save(invitation);
    }

    // generated by AI
    public List<PollResponse> getPendingPolls(String username) {
        User user = userService.findEntityByUsername(username);

        return invitationRepository.findByInvitee(user)
                .stream()
                .map(Invitation::getPoll)
                .filter(poll -> !poll.isFinished())
                .filter(poll -> !participationRepository.existsByPollAndParticipant(poll, user))
                .sorted(Comparator.comparing(Poll::getDueDate).reversed())
                .map(PollMapper::toResponse)
                .toList();
    }
}