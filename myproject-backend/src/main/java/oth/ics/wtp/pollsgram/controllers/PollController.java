package oth.ics.wtp.pollsgram.controllers;

import oth.ics.wtp.pollsgram.dtos.PollCreateRequest;
import oth.ics.wtp.pollsgram.dtos.PollResponse;
import oth.ics.wtp.pollsgram.services.PollService;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.*;
import oth.ics.wtp.pollsgram.dtos.PollSubmissionRequest;
import oth.ics.wtp.pollsgram.services.ParticipationService;
import oth.ics.wtp.pollsgram.dtos.ParticipationResponse;
import oth.ics.wtp.pollsgram.dtos.QuestionResultResponse;
import oth.ics.wtp.pollsgram.dtos.PollUpdateRequest;
import oth.ics.wtp.pollsgram.services.InvitationService;
import oth.ics.wtp.pollsgram.dtos.InvitationRequest;

import java.security.Principal;
import java.util.List;

@RestController
@RequestMapping("/api/polls")
public class PollController {

    private final PollService pollService;
    private final ParticipationService participationService;
    private final InvitationService invitationService;

    public PollController(
            PollService pollService,
            ParticipationService participationService,
            InvitationService invitationService
    ) {
        this.pollService = pollService;
        this.participationService = participationService;
        this.invitationService = invitationService;
    }

    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    public PollResponse createPoll(
            @RequestBody PollCreateRequest request,
            Principal principal
    ) {
        return pollService.createPoll(request, principal.getName());
    }

    @PostMapping("/{id}/invitations")
    @ResponseStatus(HttpStatus.CREATED)
    public void inviteUser(
            @PathVariable Long id,
            @RequestBody InvitationRequest request,
            Principal principal
    ) {
        invitationService.inviteUser(
                id,
                request,
                principal.getName()
        );
    }

    @GetMapping("/pending")
    public List<PollResponse> getPendingPolls(Principal principal) {
        return invitationService.getPendingPolls(principal.getName());
    }

    @PostMapping("/{id}/submit")
    @ResponseStatus(HttpStatus.CREATED)
    public void submitPoll(
            @PathVariable Long id,
            @RequestBody PollSubmissionRequest request,
            Principal principal
    ) {
        participationService.submitPoll(id, request, principal.getName());
    }

    @GetMapping("/my")
    public List<PollResponse> getMyPolls(Principal principal) {
        return pollService.findMyPolls(principal.getName());
    }

    @GetMapping("/{id}")
    public PollResponse getPollById(@PathVariable Long id) {
        return pollService.findById(id);
    }

    // generated by AI
    @GetMapping("/{id}/participations")
    public List<ParticipationResponse> getParticipations(
            @PathVariable Long id,
            Principal principal
    ) {
        return participationService.getParticipationsForPoll(id, principal.getName());
    }

    // generated by AI
    @GetMapping("/{id}/results")
    public List<QuestionResultResponse> getResults(
            @PathVariable Long id,
            Principal principal
    ) {
        return participationService.getResultsForPoll(id, principal.getName());
    }

    @PostMapping("/{id}/finish")
    public PollResponse finishPoll(
            @PathVariable Long id,
            Principal principal
    ) {
        return pollService.finishPoll(id, principal.getName());
    }

    @PutMapping("/{id}")
    public PollResponse updatePoll(
            @PathVariable Long id,
            @RequestBody PollUpdateRequest request,
            Principal principal
    ) {
        return pollService.updatePoll(id, request, principal.getName());
    }

    @DeleteMapping("/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    public void deletePoll(
            @PathVariable Long id,
            Principal principal
    ) {
        pollService.deletePoll(id, principal.getName());
    }

    @GetMapping
    public List<PollResponse> getAvailablePolls(Principal principal) {
        return pollService.findAvailablePolls(principal.getName());
    }

    @GetMapping("/my-submissions")
    public List<ParticipationResponse> getMySubmissions(Principal principal) {
        return participationService.getMyParticipations(principal.getName());
    }
}